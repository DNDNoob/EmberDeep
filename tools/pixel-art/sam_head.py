def star(cx,cy,R,rot=-90,ratio=0.42):
    pts=[]
    for i in range(10):
        r=R if i%2==0 else R*ratio
        a=math.radians(rot+i*36); pts.append((cx+r*math.cos(a),cy+r*math.sin(a)))
    return pts

def block_mode(lab, w=W, h=H):
    sy=lab.shape[0]/h; sx=lab.shape[1]/w
    out=np.zeros((h,w),int)
    for y in range(h):
        for x in range(w):
            blk=lab[int(y*sy):int((y+1)*sy), int(x*sx):int((x+1)*sx)]
            out[y,x]=np.bincount(blk.ravel(),minlength=32).argmax()
    return out

