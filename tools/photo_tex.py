"""Turn Forge tiling images into game textures: evens out lighting, writes a colour JPEG and a height JPEG
for each surface into src/photos/, and src/photos.js with them inlined as data URLs.
Run: python3 tools/photo_tex.py   (needs Pillow and numpy)"""
import base64, io, json, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'src')
# game texture layer -> (source image, roughness, height contrast, darken gaps)
PICK = {
    0:  ('forge-1412.png', 0.92, 1.0),   # Old Stonework wall
    1:  ('forge-1415.png', 0.88, 1.0),   # Old Stonework floor
    13: ('forge-1418.png', 0.85, 0.35),  # Humming Rooms wallpaper
}
SIZE = 1024

def blur_wrap(a, r):
    """Gaussian blur of a tileable image (FFT, so it wraps at the edges)."""
    h, w = a.shape[:2]
    fy = np.fft.fftfreq(h)[:, None]; fx = np.fft.fftfreq(w)[None, :]
    g = np.exp(-2 * (np.pi * r) ** 2 * (fx ** 2 + fy ** 2))
    if a.ndim == 3: g = g[..., None]
    return np.real(np.fft.ifft2(np.fft.fft2(a, axes=(0, 1)) * g, axes=(0, 1))).astype(np.float32)

def jpeg(arr, q, mode):
    im = Image.fromarray(np.clip(arr * 255 + .5, 0, 255).astype(np.uint8), mode)
    b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True, progressive=True)
    return b.getvalue()

out = {}
for layer, (name, rough, hk) in PICK.items():
    img = Image.open(os.path.join(SRC, name)).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS)
    a = np.asarray(img).astype(np.float32) / 255
    lin = a ** 2.2
    # even out broad lighting gradients the model painted in: divide by a wide blur, keep the overall mean
    lum = lin @ np.array([.2126, .7152, .0722], np.float32)
    low = blur_wrap(lum, SIZE / 10)
    lin = lin * (lum.mean() / np.maximum(low, 1e-3))[..., None]
    alb = np.clip(lin, 0, 1) ** (1 / 2.2)
    # height: local luminance contrast (dark joints sit low, faces high), softened
    l = alb @ np.array([.2126, .7152, .0722], np.float32)
    l = blur_wrap(l, 1.2)
    loc = blur_wrap(l, 18)
    sd = np.sqrt(np.maximum(blur_wrap((l - loc) ** 2, 18), 1e-5))
    z = (l - loc) / sd
    hgt = 1 / (1 + np.exp(-1.6 * z * hk))
    if hk >= 1:  # stone: wide blocks stay flat on top, joints drop away
        # joints are the darkest, widest dips: find them from a soft threshold, then round the block edges
        joint = 1 / (1 + np.exp(-3.0 * (z + .9)))          # 0 in joints, 1 on faces
        hgt = blur_wrap(joint, 2.5) * .8 + .2 * blur_wrap(hgt, 3.0)
    hgt = (hgt - hgt.min()) / (hgt.max() - hgt.min())
    if hk < 1:  # paper: only a faint emboss, so keep it soft and small
        hgt = .5 + (blur_wrap(hgt, 2.5) - .5) * .5
        hgt = np.asarray(Image.fromarray((hgt * 255).astype(np.uint8)).resize((SIZE // 2, SIZE // 2), Image.LANCZOS)).astype(np.float32) / 255
    os.makedirs(os.path.join(ROOT, 'assets', 'photos'), exist_ok=True)
    ab, hb = jpeg(alb, 84, 'RGB'), jpeg(hgt, 82, 'L')
    open(os.path.join(ROOT, 'assets', 'photos', f'{layer}_alb.jpg'), 'wb').write(ab)
    open(os.path.join(ROOT, 'assets', 'photos', f'{layer}_h.jpg'), 'wb').write(hb)
    out[layer] = {'alb': 'data:image/jpeg;base64,' + base64.b64encode(ab).decode(),
                  'h': 'data:image/jpeg;base64,' + base64.b64encode(hb).decode(), 'rough': rough}
    print(layer, name, len(ab) // 1024, 'KB colour', len(hb) // 1024, 'KB height')

with open(os.path.join(ROOT, 'src', 'photos.js'), 'w') as f:
    f.write('// Generated by tools/photo_tex.py from Forge (SDXL) tiling images in assets/src. Do not edit by hand.\n')
    f.write('export const PHOTOS = ' + json.dumps({str(k): v for k, v in out.items()}) + ';\n')
